"""Generate original short physical-dice cues from seeded noise and decaying resonances.

Assets generated by this script are original Cubetable assets released under CC0 1.0.
Requires Python 3 and ffmpeg only. No recordings or external samples.
"""
import math, random, struct, subprocess, tempfile, wave
from pathlib import Path

RATE=22050
OUT=Path(__file__).resolve().parents[1]/'src/main/resources/assets/tacticalcombat/sounds'
CUES={
 'dice_move':(.26,[(.03,.19,940,.34),(.10,.12,670,.25)]),
 'dice_clatter':(.39,[(.015,.12,1170,.50),(.085,.11,730,.35),(.16,.10,980,.27),(.24,.08,570,.22)]),
 'dice_impact':(.28,[(.01,.23,410,.75),(.035,.16,690,.35)]),
 'dice_bounce':(.17,[(.008,.12,570,.42)]),
 'dice_settle':(.25,[(.025,.18,810,.24),(.095,.12,1210,.11)]),
}
OUT.mkdir(parents=True,exist_ok=True)
for index,(name,(duration,impacts)) in enumerate(CUES.items()):
 rng=random.Random(142700+index)
 data=[]
 for i in range(int(duration*RATE)):
  t=i/RATE; sample=0.
  for start,decay,freq,volume in impacts:
   if t<start:continue
   age=t-start; envelope=math.exp(-age/decay)*min(1,age*800)
   metal=math.sin(2*math.pi*freq*age)+.24*math.sin(2*math.pi*freq*2.72*age)
   noise=rng.uniform(-1,1)
   sample+=volume*envelope*(metal*.55+noise*.20)
  data.append(int(max(-1,min(1,sample)) * 28000))
 with tempfile.NamedTemporaryFile(suffix='.wav') as temp:
  with wave.open(temp.name,'wb') as wav:
   wav.setnchannels(1);wav.setsampwidth(2);wav.setframerate(RATE)
   wav.writeframes(struct.pack('<'+'h'*len(data),*data))
  subprocess.run(['ffmpeg','-v','error','-y','-i',temp.name,'-c:a','libvorbis','-q:a','4',str(OUT/(name+'.ogg'))],check=True)
